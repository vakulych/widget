function touchSession(sessionId) {
  lastSeen.set(sessionId, Date.now());
}

function cleanupOldSessions() {
  const cutoff = Date.now() - SESSION_TTL_MS;
  let removed = 0;
  for (const [sessionId, ts] of lastSeen) {
    if (ts < cutoff) {
      lastSeen.delete(sessionId);
      sessions.delete(sessionId);
      sessionScope.delete(sessionId);
      removed++;
    }
  }
  if (removed) console.log(`[chat] Прибрано неактивних сесій: ${removed} (лишилось ${sessions.size}).`);
}

const cleanupTimer = setInterval(cleanupOldSessions, SESSION_CLEANUP_INTERVAL_MS);
if (cleanupTimer.unref) cleanupTimer.unref();

function getScope(sessionId) {
  return sessionScope.get(sessionId) || { category: null, brand: null, budgetMin: null, budgetMax: null, condition: null, nodeKey: null };
}
function updateScope(sessionId, patch) {
  const prev = getScope(sessionId);
  const next = {
    category: patch.category ?? prev.category ?? null,
    brand: patch.brand ?? prev.brand ?? null,
    budgetMin: patch.budgetMin ?? prev.budgetMin ?? null,
    budgetMax: patch.budgetMax ?? prev.budgetMax ?? null,
    // гілка дерева категорій: нова категорія без ключа скидає стару гілку, інакше "до 1000 грн" лишається в ній
    nodeKey: Object.prototype.hasOwnProperty.call(patch, "nodeKey")
      ? patch.nodeKey
      : patch.category && patch.category !== prev.category
      ? null
      : prev.nodeKey ?? null,
     
     
    condition: Object.prototype.hasOwnProperty.call(patch, "condition") ? patch.condition : prev.condition ?? null,
  };
  sessionScope.set(sessionId, next);
  return next;
}

