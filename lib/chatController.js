// ── Дерево категорій: кнопки підкатегорій + точний пошук у потрібній гілці ──────────────────────────
// Пристрої, для яких вже є налагоджена стара логіка (марка/модель/бренд-чипи) — її не чіпаємо.
const LEGACY_DEVICE_KINDS = ["смартфон", "ноутбук", "навушники", "годинник", "планшет", "консоль"];
function isLegacyDeviceCategory(text) {
  const t = String(text || "").toLowerCase();
  return LEGACY_DEVICE_KINDS.some((k) => t.startsWith(k));
}
// «Аксесуари для iPhone» — це розділ каталогу, а не сам пристрій: тут дерево доповнює стару логіку.
const ACCESSORY_SECTION_RE = /аксес+уар/iu;

const NODE_LLM_SYSTEM_PROMPT = `Ти — модуль вибору розділу каталогу інтернет-магазину Skay.ua.
Тобі дають повідомлення клієнта і СПИСОК РОЗДІЛІВ каталогу у форматі "ключ | Розділ › Підрозділ". Існують ЛИШЕ ці ключі.
Клієнт може писати сленгом, російською, з помилками. Обери ОДИН ключ найточнішого (найглибшого) розділу, де лежить те, що він шукає.
Якщо жоден розділ явно не підходить — поверни null.
Відповідай СУВОРО валідним JSON, без пояснень: {"key": "<ключ зі списку>"} або {"key": null}`;
const NODE_LLM_RESPONSE_SCHEMA = {
  type: "OBJECT",
  properties: { key: { type: "STRING", nullable: true } },
  required: ["key"],
};
const nodeLlmCache = new Map();

async function guessNodeWithLLM(message, catalog) {
  const cacheKey = String(message || "").trim().toLowerCase();
  if (!cacheKey) return null;
  const hit = nodeLlmCache.get(cacheKey);
  if (hit && Date.now() - hit.ts < CATEGORY_LLM_CACHE_TTL_MS) return hit.value;
  let value = null;
  try {
    const lines = categoryTree.listForLLM(catalog);
    if (lines.length) {
      const raw = await gemini.chat({
        cacheKey: "category-node-llm",
        systemInstruction: NODE_LLM_SYSTEM_PROMPT,
        jsonMode: true,
        responseSchema: NODE_LLM_RESPONSE_SCHEMA,
        temperature: 0,
        maxTokens: 40,
        userText: `Повідомлення клієнта: "${message}"\n\nРозділи:\n${lines.join("\n")}`,
      });
      const parsed = safeParseJson(raw);
      if (parsed && typeof parsed.key === "string") value = categoryTree.getNode(parsed.key);
    }
  } catch (err) {
    console.error("[chat] category node LLM fallback error:", err.message);
  }
  nodeLlmCache.set(cacheKey, { value, ts: Date.now() });
  return value;
}

// Яка гілка дерева відповідає запиту. null → працює стара логіка без змін.
function resolveTreeScope({ message, normalizedText, intent, forcedNode, catalog, products }) {
  if (!categoryTree.enabled()) return null;
  if (forcedNode) {
    return {
      node: forcedNode, nodes: [forcedNode], strictTokens: [], itemTokens: [], aliasItemTokens: [], contextTokens: [],
      coverage: 1, forced: true, brand: search.guessBrandFromText(message, products) || null,
    };
  }
  const accessorySection = ACCESSORY_SECTION_RE.test(message);
  if (!accessorySection && (isLegacyDeviceCategory(search.guessCategoryFromText(message)) || isLegacyDeviceCategory(search.guessCategoryFromText(normalizedText)))) return null;
  if (!accessorySection && isLegacyDeviceCategory(intent.category)) return null;
  const brandFromText = search.guessBrandFromText(message, products);
  const brandWords = [intent.brand, brandFromText]
    .filter(Boolean)
    .flatMap((b) => String(b).toLowerCase().split(/[^\p{L}\p{N}]+/u))
    .filter((w) => w.length > 1);
  const texts = [message, intent.semantic_query, intent.search_text, normalizedText, intent.category];
  const found = categoryTree.route(texts, { dropTokens: brandWords, catalog });
  if (found) found.brand = brandFromText || null;
  return found;
}

function brandsByFrequency(products, max = 8) {
  const counts = new Map();
  for (const p of products) {
    const v = String(p.vendor || "").trim();
    if (v) counts.set(v, (counts.get(v) || 0) + 1);
  }
  return [...counts.entries()].sort((a, b) => b[1] - a[1]).slice(0, max).map(([v]) => v);
}

// Відповідь на «широкий» запит / натискання кнопки підкатегорії. Без LLM: швидко й без вигадок.
function buildCategoryReply({ sessionId, node, mode, catalog, fromClick, asked = null }) {
  const b = categoryTree.browse(node, catalog, { mode });
  let reply;
  let cards = [];
  let filters = null;
  // «Саме "X" не знайшов, але ось що є в розділі…» — коли клієнт просив конкретний предмет, а його нема.
  const missPrefix = asked ? `Саме «${asked}» зараз не знайшов 🤷 ` : null;

  if (b.type === "ask") {
    reply = missPrefix
      ? `${missPrefix}Зате в розділі «${b.node.ua}» є ${b.total} ${productCountWord(b.total)} — оберіть підкатегорію:`
      : fromClick
      ? `«${b.node.ua}» — тут кілька напрямків, разом ${b.total} ${productCountWord(b.total)} в наявності. Що саме цікавить?`
      : `Так, у нас є розділ «${b.node.ua}» — зараз в наявності ${b.total} ${productCountWord(b.total)}. Що саме вас цікавить? Оберіть підкатегорію, і я покажу, що є:`;
    filters = { options: b.options, optionsLabel: "Оберіть підкатегорію:", nodeKey: b.node.k, brands: [], priceRanges: [] };
  } else if (b.type === "list") {
    const all = b.products.filter((p) => p.price != null);
    const picks = search.rankAndDiversify(all, { queryText: "", brand: null, vectorScores: null, limit: 8 });
    cards = picks.map((p) => toCard(p, null));
    const prices = all.map((p) => p.price);
    const range = prices.length > 1 ? `, ціни від ${Math.min(...prices)} до ${Math.max(...prices)} грн` : "";
    const title = b.direct ? (b.node.dl ? `${b.node.ua}: ${b.node.dl.toLowerCase()}` : `${b.node.ua} (інше)`) : b.node.ua;
    reply = missPrefix
      ? `${missPrefix}Зате в розділі «${title}» є ${all.length} ${productCountWord(all.length)}${range} — ось що є:`
      : all.length > picks.length
      ? `«${title}»: в наявності ${all.length} ${productCountWord(all.length)}${range}. Показую ${picks.length} — напишіть бренд чи бюджет, і я підберу точніше.`
      : `«${title}»: ось усе, що зараз є в наявності (${all.length} ${productCountWord(all.length)}${range}).`;
    const brands = brandsByFrequency(all);
    const priceRanges = buildPriceRanges(all);
    filters = {
      brands: brands.length > 1 ? brands : [],
      priceRanges: priceRanges || [],
      category: b.node.ua,
      nodeKey: b.node.k,
    };
    if (b.back) {
      filters.options = [b.back];
      filters.optionsLabel = "Повернутись:";
    }
  } else {
    reply = `У розділі «${b.node.ua}» зараз немає товарів в наявності. Можу показати найближчі розділи, де щось є:`;
    filters = { options: b.options, optionsLabel: "Є в наявності:", brands: [], priceRanges: [] };
  }

  updateScope(sessionId, { category: b.node.ua, nodeKey: b.node.k });
  return {
    reply,
    products: cards,
    intent: { intent: "recommendation", category: b.node.ua, confidence: 1 },
    filters,
  };
}

// ── Детермінований пошук по каталогу (productFinder) ────────────────────────────
// Запити «звичайним словом» (кастрюли, сковородки, нож, шредер, утюг...) розбираються напряму по
// каталогу, без LLM-ланцюжка, у якому будь-яка помилка перетворювалась на «такого немає».
// Нижче — коли ця гілка НЕ береться за запит: там вже є налагоджена спеціалізована логіка.
function finderEligible(message, normalizedText) {
  const text = String(message || "");
  if (ACCESSORY_REQUEST_RE.test(text) || ACCESSORY_REQUEST_RE.test(normalizedText)) return false;
  if (NOVELTY_RE.test(normalizedText) || SALE_RE.test(normalizedText)) return false;
  if (IDENTITY_PROBE_RE.test(text) || RECONSIDER_RE.test(text.trim())) return false;
  if (requestedCondition(text)) return false; // б/в — окрема логіка
  if (finder.hasContextWord(text)) return false; // «для собаки / для дитини» — дерево з контекстом
  // Do not reserve whole product families for the legacy path. The catalogue
  // finder understands every category and gives the same typo/RU-UA/attribute
  // behaviour to a laptop, a pan and a smartphone. Model-like bare numbers
  // still go to the specialised exact-model branch below.
  // Preserve a bare number for exact model lookup ("iPhone 16"), but let
  // technical constraints such as "144 Гц", "256 GB" and "55 дюймів"
  // enter the universal finder where they are enforced before ranking.
  const remaining = finder
    .parseBudget(normalizedText).rest
    .replace(/\d{1,6}\s*(?:hz|гц|герц|gb|гб|tb|тб|mah|ма\s*г|["″]|дюйм\p{L}*|inch(?:es)?)/giu, " ");
  if (/\d/.test(remaining)) return false;
  return true;
}

function hasHardConstraint(text) {
  const c = finder.parseHardConstraints(finder.parseBudget(text).rest);
  return c.storageGb != null || c.capacityMah != null || c.diagonalInches != null || c.refreshHz != null;
}

function constraintRequestLabel(text) {
  const source = String(text || "");
  const budget = finder.parseBudget(source);
  const c = finder.parseHardConstraints(budget.rest);
  let product = "товар";
  if (/(?:ноутбук|ноут|laptop|macbook|chromebook)/iu.test(source)) product = "ноутбук";
  else if (/(?:смартфон|телефон|iphone|айфон)/iu.test(source)) product = "смартфон";
  else if (/(?:монітор|монитор)/iu.test(source)) product = "монітор";
  else if (/(?:телевізор|телевизор|\btv\b)/iu.test(source)) product = "телевізор";

  const details = [];
  if (c.refreshHz != null) details.push("з екраном " + c.refreshHz + " Гц");
  if (c.storageGb != null) details.push("з памʼяттю " + c.storageGb + " GB");
  if (c.diagonalInches != null) details.push("з діагоналлю " + c.diagonalInches + "\"");
  if (c.capacityMah != null) details.push("з акумулятором " + c.capacityMah + " mAh");
  if (budget.max != null) details.push("до " + budget.max.toLocaleString("uk-UA") + " грн");
  if (budget.min != null) details.push("від " + budget.min.toLocaleString("uk-UA") + " грн");
  return details.length ? product + " " + details.join(", ") : product;
}

function buildConstraintMissResponse({ sessionId, message, catalog, rawMessage }) {
  const phrase = constraintRequestLabel(message);
  const reply =
    "За точними умовами — " + phrase + " — зараз нічого немає в наявності. " +
    "Не показуватиму моделі з іншими характеристиками. Можу підібрати найближчий варіант, якщо зміните одну з умов — наприклад частоту екрана або бюджет.";
  pushHistory(sessionId, "user", rawMessage);
  pushHistory(sessionId, "assistant", reply);
  return {
    reply,
    products: [],
    intent: { intent: "recommendation", confidence: 1, source: "finder-constraint-miss" },
    filters: null,
  };
}

function buildFinderResponse({ sessionId, r, message, catalog, rawMessage }) {
  const unavailable = r.tier === "unavailable";
  let reply = finder.composeReply(r, message);
  let visibleItems = uniqueProducts(r.picks);
  // Для вузьких назв категорій не підмішуємо товари із сусідньої категорії лише через
  // семантичну схожість («яйцеварка» не є мультиваркою, навіть якщо обидва для кухні).
  if (/мультиварк/iu.test(message)) visibleItems = visibleItems.filter((p) => /мультиварк/iu.test(p.name || ""));
  if (/волейбол/iu.test(message)) visibleItems = visibleItems.filter((p) => /волейбол/iu.test(p.name || ""));
  if (/мультиварк|волейбол/iu.test(message) && visibleItems.length !== r.picks.length && !unavailable) {
    reply = visibleItems.length
      ? `Знайшла ${visibleItems.length} точних варіантів за вашим запитом. Показую лише товари з цієї категорії.`
      : "Точних варіантів за вашим запитом зараз немає в наявності.";
  }
  const cards = unavailable ? [] : [
    ...visibleItems.map((p) => toCard(p, p._tag || (r.tier === "related" ? "схоже" : null))),
  ];
  let filters = null;
  if (!unavailable && r.tier !== "related") {
    const brands = brandsByFrequency(r.items);
    const priceRanges = buildPriceRanges(r.items);
    const options = [];
    // розділи, у яких лежать знайдені товари (лише коли розділ майже весь складається зі знайденого)
    if (r.total > r.picks.length) {
      const perNode = new Map();
      for (const p of r.items) {
        const n = categoryTree.nodeOfProduct(p);
        if (n) perNode.set(n.k, (perNode.get(n.k) || 0) + 1);
      }
      if (perNode.size > 1) {
        for (const [k, found] of [...perNode.entries()].sort((a, b) => b[1] - a[1]).slice(0, 6)) {
          const node = categoryTree.getNode(k);
          if (node && found >= 2 && found / Math.max(1, categoryTree.countOf(node, catalog)) >= 0.5) options.push(categoryTree.chip(node, catalog));
        }
      }
    }
    if (brands.length > 1 || priceRanges || options.length > 1) {
      filters = {
        brands: brands.length > 1 ? brands : [],
        priceRanges: priceRanges || [],
        category: r.tokens.join(" "),
        brand: null,
        budgetMin: r.budget.min || null,
        budgetMax: r.budget.max || null,
      };
      if (options.length > 1) {
        filters.options = options;
        filters.optionsLabel = "Уточнити розділ:";
      }
    }
  }
  if (!unavailable) {
    updateScope(sessionId, {
      category: (r.node && r.node.ua) || r.tokens.join(" "),
      brand: null,
      budgetMin: r.budget.min || null,
      budgetMax: r.budget.max || null,
      nodeKey: r.node ? r.node.k : null,
    });
  }
  pushHistory(sessionId, "user", rawMessage);
  pushHistory(sessionId, "assistant", reply);
  // Якщо клієнт цікавиться айфонами — знизу пропонуємо здати старий у трейд-ін
  const aboutIphone = !unavailable && r.items.some((p) => /iphone/i.test(p.name) && !p.isAccessory);
  const quickReplies = aboutIphone
    ? [{ label: "Оцінити мій старий iPhone у трейд-ін", text: "хочу здати айфон у трейд-ін" }]
    : [];
  return {
    reply,
    products: cards,
    intent: { intent: "recommendation", category: r.tokens.join(" "), confidence: 1, source: "finder" },
    filters,
    quickReplies,
  };
}

// The deterministic finder is responsible for correctness (model, price,
// availability and compatibility). Once it has built a safe candidate set, a
// vector score can make the order feel human: for example, it can prefer a
// light practical laptop for a request \"для навчання\" without allowing a
// non-laptop into the results.
async function applySemanticFinderRank(result, query) {
  if (!result || !result.items || !result.items.length || !embeddings.isReady()) return result;
  try {
    const vector = await embeddings.embedQuery(query);
    if (!vector) return result;
    const semantic = embeddings.scoreAgainst(vector, result.items);
    if (!semantic.size) return result;

    const lexicalPosition = new Map(result.items.map((p, i) => [p.id, i]));
    const count = Math.max(1, result.items.length - 1);
    const ranked = [...result.items]
      .map((p) => {
        const lexical = 1 - (lexicalPosition.get(p.id) || 0) / count;
        // Exact retrieval remains the dominant signal. Semantics improve ties
        // and broad human requests only after all hard filters have passed.
        return { p, score: lexical * 0.55 + Math.max(0, semantic.get(p.id) || 0) * 0.45 };
      })
      .sort((a, b) => b.score - a.score || a.p.price - b.p.price);

    // Preserve result diversity without reintroducing anything outside the
    // verified candidate set.
    const perVendor = new Map();
    const picks = [];
    for (const { p } of ranked) {
      const vendor = String(p.vendor || "інше").toLowerCase();
      if ((perVendor.get(vendor) || 0) >= 2) continue;
      picks.push(p);
      perVendor.set(vendor, (perVendor.get(vendor) || 0) + 1);
      if (picks.length === 8) break;
    }
    result.picks = picks.length ? picks : result.picks;
  } catch (err) {
    console.warn("[chat] semantic finder rank skipped:", err.message);
  }
  return result;
}

function buildMissInSection({ sessionId, node, message, catalog, rawMessage }) {
  const phrase = finder.askedPhrase(message) || String(message || "").trim().slice(0, 40);
  const nav = buildCategoryReply({ sessionId, node, mode: "browse", catalog, fromClick: true, asked: phrase });
  pushHistory(sessionId, "user", rawMessage);
  pushHistory(sessionId, "assistant", nav.reply);
  return nav;
}

// Нічого не знайшли жодним способом: або «ось найближчий розділ», або чесно й з гумором «такого в нас нема».
async function buildNotFoundResponse({ sessionId, message, catalog, rawMessage }) {
  const phrase = finder.askedPhrase(message) || String(message || "").trim().slice(0, 40);
  let node = null;
  try {
    node = await guessNodeWithLLM(message, catalog);
  } catch {
    node = null;
  }
  let out;
  if (node && categoryTree.countOf(node, catalog) > 0) {
    out = buildCategoryReply({ sessionId, node, mode: "browse", catalog, fromClick: true, asked: phrase });
  } else {
    out = {
      reply: finder.composeNotFound(message, { vocabKnown: finder.anyWordKnown(catalog, message) }),
      products: [],
      intent: { intent: "other", confidence: 1, source: "finder" },
      filters: { options: categoryTree.topSections(catalog), optionsLabel: "Розділи каталогу:", brands: [], priceRanges: [] },
    };
  }
  pushHistory(sessionId, "user", rawMessage);
  pushHistory(sessionId, "assistant", out.reply);
  return out;
}

async function handleMessage({ sessionId, message, catalog, categoryKey = null, categoryMode = null }) {
  touchSession(sessionId);
  const history = getHistory(sessionId);
  const rawMessage = message;

  const isIdentityProbe = IDENTITY_PROBE_RE.test(String(rawMessage || ""));

  // Якщо клієнт просить "подумати"/"пошукати ще раз" — підміняємо запит на його попереднє
  // РЕАЛЬНЕ повідомлення (не саму фразу "думай") і прожене його через увесь пайплайн заново,
  // з приміткою для фінальної відповіді (див. contextBlock нижче). В історію запишеться
  // те, що клієнт фактично написав (rawMessage), а не підміна.
  let isReconsider = false;
  if (RECONSIDER_RE.test(String(message || "").trim())) {
    const priorUser = [...history].reverse().find(
      (m) => m.role === "user" && !RECONSIDER_RE.test(String(m.content || "").trim())
    );
    if (priorUser) {
      message = priorUser.content;
      isReconsider = true;
    } else {
      const replyText = "Звісно! Підкажіть, будь ласка, що саме підібрати — категорію, бренд чи бюджет 🙂";
      pushHistory(sessionId, "user", rawMessage);
      pushHistory(sessionId, "assistant", replyText);
      return { reply: replyText, products: [], intent: { intent: "smalltalk", confidence: 1 }, filters: null };
    }
  }

  // Клік по кнопці підкатегорії: клієнт надсилає ключ вузла дерева. Без LLM показуємо наступний рівень
  // кнопок або товари. Якщо mode не заданий (кнопки бренду/ціни) — це лише обмеження пошуку гілкою.
  let forcedNode = null;
  if (categoryKey && categoryTree.enabled()) {
    forcedNode = categoryTree.getNode(categoryKey);
    if (forcedNode && categoryMode) {
      const nav = buildCategoryReply({ sessionId, node: forcedNode, mode: categoryMode, catalog, fromClick: true });
      pushHistory(sessionId, "user", rawMessage);
      pushHistory(sessionId, "assistant", nav.reply);
      return nav;
    }
  }

  const messageCondition = requestedCondition(message);

  // Запит на оператора ніколи не повинен потрапляти в пошук каталогу. Раніше окрема
  // відповідь була лише поза робочим часом, тому вдень фраза з кнопки могла пройти
  // через загальний пошук і видати випадкові товари.
  if (OPERATOR_CONNECT_RE.test(message)) {
    const availableNow = isOperatorHoursNow();
    const replyText = availableNow
      ? "Зараз з'єднаю з оператором. Оберіть зручний спосіб зв'язку нижче — менеджер відповість якнайшвидше."
      : "Зараз оператори вже не на зв'язку — працюємо з 10:00 до 20:00. Але ви можете залишити повідомлення в Telegram, і менеджер відповість, щойно почнеться робочий день.";
    pushHistory(sessionId, "user", rawMessage);
    pushHistory(sessionId, "assistant", replyText);
    return {
      reply: replyText,
      products: [],
      intent: { intent: "other", confidence: 1, source: "operator-connect" },
      filters: null,
    };
  }

  // Не перетворюємо думку клієнта на пошуковий запит. Це стоїть перед finder/LLM,
  // щоб слова кольору, моделі чи бренду з такої репліки не дали сторонню товарну видачу.
  if (isConversationalOpinion(message)) {
    const replyText =
      "Так, розумію 🙂 Якщо захочете, можу допомогти порівняти варіанти з попередньої добірки або уточнити наявність потрібного кольору.";
    pushHistory(sessionId, "user", rawMessage);
    pushHistory(sessionId, "assistant", replyText);
    return {
      reply: replyText,
      products: [],
      intent: { intent: "smalltalk", confidence: 1, source: "conversational-opinion" },
      filters: null,
    };
  }

  // Прайс трейд-іну має власний діалог з трьома контрольними питаннями. Він іде
  // раніше за каталог, інакше «хочу здати iPhone» перетворюється на пошук нових телефонів.
  const tradeInReply = tradeIn.step({ sessionId, message });
  if (tradeInReply) {
    pushHistory(sessionId, "user", rawMessage);
    pushHistory(sessionId, "assistant", tradeInReply.reply);
    return {
      reply: tradeInReply.reply,
      products: [],
      intent: { intent: "tradein", confidence: 1, source: "tradein-flow" },
      filters: null,
      quickReplies: tradeInReply.quickReplies || [],
    };
  }

  // Нечітке слово не має перетворюватися на довільну категорію. Краще одне коротке
  // уточнення, ніж помилково видати машинки для стрижки замість того, що мав на увазі клієнт.
  if (/стрилк/iu.test(message)) {
    const reply = "Не до кінця зрозуміла «стрилка». Ви маєте на увазі машинку для стрижки, стрічку або щось інше?";
    pushHistory(sessionId, "user", rawMessage);
    pushHistory(sessionId, "assistant", reply);
    return { reply, products: [], intent: { intent: "smalltalk", confidence: 1, source: "ambiguous-typo" }, filters: null };
  }

  const strictBrandReply = buildStrictBrandResponse({ sessionId, message, catalog, rawMessage });
  if (strictBrandReply) return strictBrandReply;

  const strictAccessoryReply = buildStrictIphoneAccessoryResponse({ sessionId, message, catalog, rawMessage });
  if (strictAccessoryReply) return strictAccessoryReply;

  const iphoneReply = buildIphoneResponse({ sessionId, message, catalog, rawMessage });
  if (iphoneReply) return iphoneReply;

  // Пошук за артикулом/кодом товару — пряме, детерміноване зіставлення з vendorCode/id,
  // в обхід текстового пошуку (цифровий код майже ніколи не збігається зі словами в назві).
  const articleMatch = ARTICLE_QUERY_RE.exec(message);
  if (articleMatch) {
    const code = articleMatch[1];
    const product = findByArticle(catalog, code);
    let replyText;
    let cards = [];
    if (product) {
      cards = [toCard(product, null)];
      const priceText = product.price ? ` — ${product.price} грн` : "";
      replyText = `Знайшла за артикулом ${code}: ${product.name}${priceText}.`;
    } else {
      replyText = `За артикулом ${code} зараз нічого не знайшлося в каталозі. Перевірте, будь ласка, номер, або напишіть назву товару — підберу за нею.`;
    }
    pushHistory(sessionId, "user", rawMessage);
    pushHistory(sessionId, "assistant", replyText);
    return {
      reply: replyText,
      products: cards,
      intent: { intent: product ? "specific_product" : "other", confidence: 1, source: "article-lookup" },
      filters: null,
    };
  }

  // Питання про послугу поклейки захисного скла/плівки — детермінована відповідь,
  // без звернення до пошуку товарів чи LLM (див. isProtectorInstallQuestion вище).
  if (isProtectorInstallQuestion(message)) {
    const replyText =
      "Поклейка захисного скла чи плівки безкоштовна в будь-якому магазині Skay.ua в Одесі, якщо скло придбане у нас 🩷 Також можемо наклеїти його заздалегідь, ще до відправлення Новою Поштою — просто попередьте про це менеджера при оформленні замовлення.";
    pushHistory(sessionId, "user", rawMessage);
    pushHistory(sessionId, "assistant", replyText);
    return {
      reply: replyText,
      products: [],
      intent: { intent: "other", confidence: 1, source: "glass-install" },
      filters: null,
    };
  }

   
  const { normalizedText, matches: slangMatches } = slang.normalizeSlang(message);

  // Загальний запит про Funko POP! ("є фанко?") → спочатку уточнюємо серію; клік по серії → її товари.
  // Без звернення до LLM. Конкретні запити ("funko marvel spider-man", "funko до 1000 грн") сюди не потрапляють.
  if (FUNKO_SUBCATEGORIES) {
    const fk = funko.handle(message, catalog.products || []);
    if (fk) {
      let replyText;
      let cards = [];
      let filters = null;
      if (fk.type === "ask") {
        replyText = `У нас багато Funko POP! 🎁 Зараз у наявності ${fk.total} фігурок. Що саме вас цікавить? Оберіть серію, і я покажу, що є:`;
        filters = { options: fk.options, brands: [], priceRanges: [] };
      } else {
        cards = fk.picks.map((p) => toCard(p, null));
        replyText = fk.total > fk.picks.length
          ? `Ось Funko POP! із серії «${fk.group.label}» — показую ${fk.picks.length} із ${fk.total} в наявності. Шукаєте конкретного героя чи бюджет? Напишіть, і я підберу точніше.`
          : `Ось усі Funko POP! із серії «${fk.group.label}», що зараз є в наявності.`;
      }
      pushHistory(sessionId, "user", rawMessage);
      pushHistory(sessionId, "assistant", replyText);
      return {
        reply: replyText,
        products: cards,
        intent: { intent: "recommendation", category: "funko", brand: "Funko", confidence: 1 },
        filters,
      };
    }
  }

  // Загальний запит рівня «Товари для тварин» → кнопки підкатегорій (лише ті, де є товари в наявності).
  // Пристрої зі старою логікою (смартфони, ноутбуки тощо) сюди не потрапляють.
  if (!forcedNode && categoryTree.enabled()) {
    const broad = categoryTree.matchBroad(message, catalog);
    // розділи верхнього рівня («Навушники та аудіо») показуємо кнопками завжди; вужчі пристрої
    // (смартфон, ноутбук...) лишаються на налагодженій старій логіці
    if (broad && (broad.d === 0 || ACCESSORY_SECTION_RE.test(message) || !isLegacyDeviceCategory(search.guessCategoryFromText(message)))) {
      const nav = buildCategoryReply({ sessionId, node: broad, mode: "browse", catalog, fromClick: false });
      pushHistory(sessionId, "user", rawMessage);
      pushHistory(sessionId, "assistant", nav.reply);
      return nav;
    }
  }

  // Прямий пошук по каталогу (без LLM): знаходить товар навіть якщо слово написане по-російськи,
  // з помилкою, в іншій формі чи називається в каталозі інакше. Нічого не знайшов — працює решта пайплайна.
  let finderMissed = false;
  if (!forcedNode && !isIdentityProbe && finderEligible(message, normalizedText)) {
    try {
      // ВАЖЛИВО: шукаємо по normalizedText (сленг типу "сяоми"→"Xiaomi" уже замінено), а не по
      // сирому message. Раніше тут був message — через це "блочки сяоми" шукало буквально слово
      // "сяоми" (його немає в жодній назві товару, там скрізь "Xiaomi") і завжди провалювалось,
      // хоча словник сленгу правильно розпізнавав бренд.
      let found = finder.find(catalog, normalizedText);
      found = await applySemanticFinderRank(found, normalizedText);
      if (found) return buildFinderResponse({ sessionId, r: found, message, catalog, rawMessage });
      // A recognised product family plus an unmet explicit technical
      // requirement is a trustworthy negative result. Do not fall through to
      // the broad recommender, which would display unrelated 60 Hz laptops for
      // a request explicitly asking for 144 Hz.
      if (hasHardConstraint(normalizedText) && finder.anyWordKnown(catalog, normalizedText)) {
        return buildConstraintMissResponse({ sessionId, message, catalog, rawMessage });
      }
      finderMissed = true;
    } catch (err) {
      console.error("[chat] finder error (переходимо на стару логіку):", err.message);
    }
  }

   
  let intent = {
    intent: "other",
    category: null,
    brand: null,
    model: null,
    storage_gb: null,
    budget_min: null,
    budget_max: null,
    wants_accessories: false,
    search_text: normalizedText,
    confidence: 0.5,
    clarify_question: null,
  };

  const forcedNovelty = NOVELTY_RE.test(normalizedText);
  const forcedSale = !forcedNovelty && SALE_RE.test(normalizedText);

  if (forcedNovelty) {
    intent.intent = "novelty";
    intent.confidence = 0.95;
  } else if (forcedSale) {
    intent.intent = "sale";
    intent.confidence = 0.95;
  } else {
    try {
      const intentText = await gemini.chat({
        cacheKey: "intent",
        systemInstruction: INTENT_SYSTEM_PROMPT,
        jsonMode: true,
        responseSchema: INTENT_RESPONSE_SCHEMA,
        temperature: 0.1,
        maxTokens: 400,
        history: history.slice(-4),
        userText: normalizedText,
      });
      const parsed = safeParseJson(intentText);
      if (parsed) intent = { ...intent, ...parsed };
    } catch (err) {
      console.error("[chat] intent parse error:", err.message);
    }
  }

   
   
  if (slangMatches.length > 0) {
    intent.confidence = Math.max(intent.confidence || 0, 0.85);
    intent.clarify_question = null;
  }

  // Аксесуари — лише якщо клієнт їх назвав словами; інакше LLM міг сам дописати чохли й рюкзаки
  intent.wants_accessories = intent.wants_accessories === true && ACCESSORY_TEXT_RE.test(`${normalizedText} ${message}`);

   
   
  const explicitBudgetMax = parseBudgetFromMessage(message);
  if (intent.budget_max == null && explicitBudgetMax != null) intent.budget_max = explicitBudgetMax;

   
   
   
   
   
  // НЕ форсуємо "accessory", якщо клієнт явно просить сам пристрій РАЗОМ з аксесуаром
  // ("айфон 15 із чохлом") — тоді LLM вже поставив wants_accessories:true при recommendation/
  // specific_product, і саме цей намір (пристрій, а не аксесуар) має лишитись головним.
  const bundledWithDevice =
    intent.wants_accessories === true && (intent.intent === "recommendation" || intent.intent === "specific_product");
  const accessoryRequested =
    !forcedNovelty &&
    !forcedSale &&
    !bundledWithDevice &&
    (ACCESSORY_REQUEST_RE.test(message) || ACCESSORY_REQUEST_RE.test(normalizedText));
  if (accessoryRequested) {
    intent = {
      ...intent,
      intent: "accessory",
      confidence: Math.max(intent.confidence || 0, 0.9),
      clarify_question: null,
      search_text: intent.search_text || normalizedText,
    };
  }

  const explicitAppleWatch = /(?:^|[^\p{L}\p{N}])(?:apple|епл|аппл|айпл|эпл)\s*(?:watch|вотч|вотчі|часы)(?=$|[^\p{L}\p{N}])/iu;
  if (!accessoryRequested && explicitAppleWatch.test(message)) {
    intent = {
      ...intent,
      intent: "specific_product",
      category: "годинник",
      brand: "Apple",
      model: "Apple Watch",
      search_text: "Apple Watch",
      confidence: 0.99,
      clarify_question: null,
    };
  }

   
   
   
  const explicitIphone = /(?:^|[^\p{L}\p{N}])(?:apple\s*)?(?:iphone|айфон)\s*(\d{1,2})(?:\s*(pro\s*max|про\s*макс|max|макс|pro|про|plus|плюс|mini|міні|мини))?(?=$|[^\p{L}\p{N}])/iu.exec(message);
  // Назва iPhone з номером — завжди конкретна модель. Не покладаємось тут на LLM,
  // бо інакше запит «айфон 18 про макс» може помилково піти як загальна рекомендація.
  if (!accessoryRequested && explicitIphone) {
    const iphoneVariant = String(explicitIphone[2] || "")
      .toLowerCase()
      .replace(/про/gu, "pro")
      .replace(/макс/gu, "max")
      .replace(/плюс/gu, "plus")
      .replace(/міні|мини/gu, "mini")
      .replace(/\s+/g, " ")
      .trim();
    const model = `iPhone ${explicitIphone[1]}${iphoneVariant ? ` ${iphoneVariant.replace(/\b\p{L}/gu, (letter) => letter.toUpperCase())}` : ""}`;
    intent = {
      ...intent,
      intent: "specific_product",
      category: "смартфон",
      brand: "Apple",
      model,
      search_text: model,
      confidence: 0.99,
      clarify_question: null,
    };
  }

   
   
   
   
  if (!accessoryRequested && messageCondition && (intent.intent === "other" || intent.intent === "smalltalk")) {
    intent = {
      ...intent,
      intent: "recommendation",
      category: intent.category || search.guessCategoryFromText(message),
      brand: intent.brand || search.guessBrandFromText(message, catalog.products || []),
      search_text: intent.search_text || message,
      confidence: Math.max(intent.confidence || 0, 0.95),
      clarify_question: null,
    };
  }

   
   
   
  if (!accessoryRequested && intent.intent === "other") {
    const detectedCategory = search.guessCategoryFromText(message);
    const detectedBrand = search.guessBrandFromText(message, catalog.products || []);
    if (detectedCategory || detectedBrand) {
      intent = {
        ...intent,
        intent: "recommendation",
        category: intent.category || detectedCategory,
        brand: intent.brand || detectedBrand,
        confidence: Math.max(intent.confidence || 0, 0.9),
        clarify_question: null,
      };
    }
  }

   
   
  const explicitAirPods = /(?:^|[^\p{L}\p{N}])(?:apple\s*)?(?:airpods|аирподс|айрподс|эйрподс)\s+(4|pro\s*3|max(?:\s*2)?)(?=$|[^\p{L}\p{N}])/iu.exec(message);
  if (!accessoryRequested && explicitAirPods) {
    const model = `AirPods ${explicitAirPods[1].replace(/\s+/g, " ").trim()}`;
    intent = {
      ...intent,
      intent: "specific_product",
      category: "навушники",
      brand: "Apple",
      model,
      search_text: model,
      confidence: 0.99,
      clarify_question: null,
    };
  }

  const products = catalog.products || [];
   
   
   
  let effectiveCondition = messageCondition;
  const cards = [];
  const contextLines = [];
  let suggestedFilters = null;
  let needsClarification = false;
  let noConfirmedSaleForScope = null;
  let saleCategory = null;
  let saleBrand = null;
  let recommendationSummary = null;
  let specificColorSummary = null;
  let unavailableSpecificProducts = null;
  let treeScope = null;

   
   
   
   
   
  if (intent.intent === "recommendation" || intent.intent === "specific_product") {
    // Словник CATEGORY_HINT_WORDS гарантовано веде до РЕАЛЬНОЇ категорії каталогу (кожен запис
    // у ньому перевірений на живих товарах). А те, що вигадує модель як intent.category
    // ("роутер", "маршрутизатор") — вільний текст, який часто не збігається дослівно з назвою
    // реальної категорії ("Мережеве обладнання") і тоді нічого не знаходить, хоч товар є.
    // Тому спочатку завжди пробуємо словник по сирому повідомленню, і лише якщо він мовчить —
    // довіряємо тому, що визначила модель (intent.category лишається як є).
    const hinted = search.guessCategoryFromText(message);
    // Дерево категорій: яка гілка відповідає запиту. Кнопка підкатегорії (forcedNode) діє завжди.
    if (forcedNode && intent.intent !== "specific_product") intent.intent = "recommendation";
    if (intent.intent === "recommendation" && categoryTree.enabled()) {
      treeScope = resolveTreeScope({ message, normalizedText, intent, forcedNode, catalog, products: catalog.products || [] });
      if (!treeScope && !hinted && !isLegacyDeviceCategory(intent.category)) {
        const guessed = await guessNodeWithLLM(message, catalog);
        if (guessed && finderMissed) {
          // Прямий пошук по каталогу цього слова не знайшов, а LLM лише вгадала найближчий розділ:
          // не видаємо весь розділ за «знайдене», а чесно кажемо, що саме такого нема, і показуємо розділ.
          return buildMissInSection({ sessionId, node: guessed, message, catalog, rawMessage });
        }
        if (guessed) treeScope = { node: guessed, nodes: [guessed], strictTokens: [], coverage: 1 };
      }
    }
    if (treeScope) {
      intent.category = treeScope.node.ua;
    } else if (hinted) {
      intent.category = hinted;
    } else {
      // Словник не впізнав жодного слова — питаємо LLM з повним списком РЕАЛЬНИХ категорій
      // каталогу (а не вільний текст від intent.category, який часто не збігається дослівно
      // з назвою категорії і тоді resolveCategoryIds нижче нічого не знаходить).
      const llmCategory = await guessCategoryWithLLM(message, catalog.categories);
      if (llmCategory) intent.category = llmCategory;
    }
  }

   
   
   
   
   
   
   
   
   
   
  if (intent.intent === "specific_product" && !intent.model) {
    intent.intent = "recommendation";
  }

  const lowConfidence = typeof intent.confidence === "number" && intent.confidence < 0.6;

  if (lowConfidence && intent.clarify_question) {
    needsClarification = true;
     
     
     
     
    const hint =
      intent.intent === "smalltalk" ? null : await webSearch.searchWeb(message).catch(() => null);
    contextLines.push(`Потрібне уточнення: ${intent.clarify_question}`);
    if (hint) contextLines.push(`Довідка: ${hint}`);
  } else if (intent.intent === "specific_product") {
    const searchText = [intent.brand, intent.model].filter(Boolean).join(" ") || intent.search_text;
    const { exact, alternatives, unavailable } = search.findSpecificProduct(products, {
      queryText: searchText,
      storageGb: intent.storage_gb,
      usedOnly: effectiveCondition === "used",
      newOnly: effectiveCondition !== "used",
    });

    // «Є iPhone 18 Pro Max синій?» — колір є жорстким критерієм, а не побажанням
    // для LLM. Якщо кольорів не названо, лишаємо всі варіанти, щоб у відповіді
    // показати реальну палітру з фіда.
    const exactModel = exact.filter((p) => productMatchesExactModel(p, intent.model));
    const alternativeModel = alternatives.filter((p) => productMatchesExactModel(p, intent.model));
    const unavailableModel = unavailable.filter((p) => productMatchesExactModel(p, intent.model));
    const colorFilters = requestedColors(message);
    const colorExact = exactModel.filter((p) => productMatchesRequestedColor(p, colorFilters));
    const colorAlternatives = alternativeModel.filter((p) => productMatchesRequestedColor(p, colorFilters));
    const main = colorFilters.length ? (colorExact.length ? colorExact : colorAlternatives) : exactModel.length ? exactModel : alternativeModel;
    const usedAlternative = !exactModel.length && alternativeModel.length > 0;
    const matchingUnavailable = unavailableModel.filter((p) => productMatchesRequestedColor(p, colorFilters));
    if (!main.length && matchingUnavailable.length) unavailableSpecificProducts = matchingUnavailable;

    specificColorSummary = availableVariantSummary(exactModel, intent.model || searchText);
    if (specificColorSummary && !colorFilters.length) contextLines.push(specificColorSummary);

    for (const p of main.slice(0, 10)) {
      const tag = usedAlternative ? "ЗАМІНА (інший обсяг пам'яті)" : "ЗНАЙДЕНО";
      contextLines.push(formatProductLine(p, tag));
      cards.push(toCard(p, usedAlternative ? "заміна" : "знайдено"));
    }

    if (main[0] && intent.wants_accessories) {
      const acc = search.findAccessoriesFor(products, main[0]);
      for (const a of acc) {
        contextLines.push(formatProductLine(a, "АКСЕСУАР"));
        cards.push(toCard(a, "аксесуар"));
      }
    }
  } else if (intent.intent === "accessory") {
     
     
     
    // normalizedText (не сирий message) — тому сленг типу "пс5"/"вотч" вже замінений на
    // "PlayStation 5"/"Apple Watch" і family/number-фільтр нижче зможе його впізнати.
    // The customer's original words are authoritative. An LLM may produce a useful
    // normalized query, but it must never replace an unfamiliar catalog term with a
    // guessed spelling (for example, turning «техвовен» into «Technowow»).
    // Try the raw/locally-normalized request first; use the LLM rewrite only as a
    // fallback when deterministic catalog search genuinely found nothing.
    const accessoryQueries = [...new Set([normalizedText, message, intent.search_text].filter(Boolean))];
    const accessoryQuery = accessoryQueries[0];
    // Для iPhone є точний парсер моделі/варіанта (matchesIphoneVariant) — застосовуємо його
    // одразу до ВСЬОГО каталогу аксесуарів, а не до топ-12 з "загального" пошуку: інакше
    // "чохол на iPhone 15" міг знайти лише 1 товар, бо решта топ-12 були для 15 Pro/Pro Max.
    // Для всього іншого (AirPods, Apple Watch, MacBook, Samsung тощо) — findAccessoryLoose,
    // де "родина" пристрою (airpods/watch/macbook/galaxy...) обов'язкова, щоб не підмішати
    // чужі аксесуари.
    let list = [];
    let isLoose = false;
    for (const query of accessoryQueries) {
      const isIphoneQuery = Boolean(search.iphoneModelInText(query));
      const found = isIphoneQuery
        ? search.filterAccessoriesForQuery(products, query).slice(0, 8)
        : search.findAccessoryLoose(products, query, { limit: 8 });
      if (found.length) {
        list = found;
        isLoose = !isIphoneQuery && found.topScore < 1;
        break;
      }
    }
    // "підставка" без уточнення (для чого) — родини пристрою немає, тож loose-пошук порожній.
    // Показуємо наявні підставки з каталогу, щоб не відповідати "нічого не знайшов".
    if (!list.length && /підставк|подставк/iu.test(accessoryQuery)) {
      list = products.filter((p) => p.available !== false && p.price != null && /підставк/iu.test(p.categoryName || "")).slice(0, 8);
      isLoose = list.length > 0;
    }
    for (const p of list) {
      const tag = isLoose ? "АКСЕСУАР (не точний збіг з моделлю)" : "АКСЕСУАР";
      contextLines.push(formatProductLine(p, tag));
      cards.push(toCard(p, "аксесуар"));
    }
  } else if (intent.intent === "recommendation") {
     
     
     
     
    const prevNodeKey = !intent.category && !intent.brand ? getScope(sessionId).nodeKey : null;
    if (!intent.category && !intent.brand) {
      const scope = getScope(sessionId);
      if (scope.category) intent.category = scope.category;
      if (scope.brand) intent.brand = scope.brand;
      if (intent.budget_min == null && scope.budgetMin != null) intent.budget_min = scope.budgetMin;
      if (intent.budget_max == null && scope.budgetMax != null) intent.budget_max = scope.budgetMax;
    }
    // Уточнення без нової категорії («а до 1000 грн», «подешевше») лишаємось у тій самій гілці дерева.
    if (!treeScope && categoryTree.enabled() && prevNodeKey) {
      const prevNode = categoryTree.getNode(prevNodeKey);
      if (prevNode) treeScope = { node: prevNode, nodes: [prevNode], strictTokens: [], itemTokens: [], aliasItemTokens: [], contextTokens: [], coverage: 1 };
    }
    // Бренд з тексту («блендер braun») — страховка, якщо LLM його не виділила.
    if (treeScope && treeScope.brand && !intent.brand) intent.brand = treeScope.brand;
    let picks = await recommendProducts({ products, catalog, intent, message, condition: effectiveCondition, treeScope });
    // Стара логіка нічого не знайшла і дерево ще не втручалось → просимо LLM вказати розділ дерева.
    // Так дерево підстраховує словник (сленг, незвичні слова), а не лише навпаки.
    if (!picks.length && !picks.treeEmptyNode && !treeScope && categoryTree.enabled() && !isLegacyDeviceCategory(intent.category)) {
      const guessed = await guessNodeWithLLM(message, catalog);
      if (guessed && finderMissed) return buildMissInSection({ sessionId, node: guessed, message, catalog, rawMessage });
      if (guessed) {
        treeScope = { node: guessed, nodes: [guessed], strictTokens: [], itemTokens: [], aliasItemTokens: [], contextTokens: [], coverage: 1 };
        picks = await recommendProducts({ products, catalog, intent: { ...intent, category: guessed.ua }, message, condition: effectiveCondition, treeScope });
      }
    }
    if (picks.treeEmptyNode && !picks.length) {
      // Гілка визначена, але точного збігу немає — чесно кажемо й показуємо кнопки/товари розділу.
      // Є розділ із товарами, але саме потрібного предмета в ньому немає — не підсовуємо сторонні товари
      // розділу, а показуємо кнопки батьківського розділу (щоб клієнт сам обрав найближче).
      const emptyNode = picks.treeEmptyNode;
      const upNode = picks.treeEmptyHadBranch ? categoryTree.parentOf(emptyNode) || emptyNode : emptyNode;
      const askedPhrase = finder.askedPhrase(message);
      const nav = buildCategoryReply({ sessionId, node: upNode, mode: "browse", catalog, fromClick: true, asked: askedPhrase || null });
      pushHistory(sessionId, "user", rawMessage);
      pushHistory(sessionId, "assistant", nav.reply);
      return nav;
    }
    recommendationSummary = {
      total: picks.catalogTotal || 0,
      minPrice: picks.catalogPriceMin,
      maxPrice: picks.catalogPriceMax,
      usedBudgetFallback: picks.usedBudgetFallback === true,
    };
    const shownCondition = effectiveCondition || (recommendationSummary.usedBudgetFallback ? "used" : null);
    if (picks.catalogTotal) {
      const conditionLabel = shownCondition === "used" ? "б/в " : shownCondition === "new" ? "нових " : "";
      const priceRange = picks.catalogPriceMin != null && picks.catalogPriceMax != null
        ? `; ціни від ${picks.catalogPriceMin} до ${picks.catalogPriceMax} грн`
        : "";
      contextLines.push(`ПІДСУМОК ДОБІРКИ: знайдено ${picks.catalogTotal} ${conditionLabel}позицій${priceRange}.`);
    }
    const usedAccIds = new Set();
     
     
    for (const p of picks) {
      const tag = recommendationSummary.usedBudgetFallback ? "Б/В АЛЬТЕРНАТИВА ЗА БЮДЖЕТОМ" : "ВАРІАНТ";
      contextLines.push(formatProductLine(p, tag));
      cards.push(toCard(p, recommendationSummary.usedBudgetFallback ? "б/в альтернатива" : "варіант"));
    }
     
     
     
    // Аксесуари до підбірки додаємо ТІЛЬКИ якщо клієнт сам про них просив (wants_accessories).
    // Питання "аірподси є?" не має тягнути за собою чохли.
    if (intent.wants_accessories === true && !effectiveCondition && !recommendationSummary.usedBudgetFallback) {
      for (const p of picks) {
        const acc = search.findAccessoriesFor(products, p, { limit: 2 }).filter(
          (a) => !usedAccIds.has(a.id)
        );
        for (const a of acc) {
          usedAccIds.add(a.id);
          contextLines.push(formatProductLine(a, `АКСЕСУАР до ${p.name}`));
          cards.push(toCard(a, "аксесуар"));
        }
      }
    }
     
     
     
     
     
    const seenBrands = new Set();
    for (const p of picks) {
      if (p.vendor && !seenBrands.has(p.vendor)) seenBrands.add(p.vendor);
    }
    const priceRanges = buildPriceRanges(picks);
    // Підкатегорії гілки (якщо запит ще широкий) — кнопками, як і для загальних запитів.
    let treeOptions = null;
    if (treeScope && picks.catalogTotal > 8 && !(treeScope.strictTokens || []).length && treeScope.nodes.length === 1) {
      const b = categoryTree.browse(treeScope.node, catalog);
      if (b.type === "ask" && b.node.k === treeScope.node.k) treeOptions = b.options.filter((o) => o.kind !== "back");
    }
    if (seenBrands.size > 1 || priceRanges || (treeOptions && treeOptions.length)) {
      suggestedFilters = {
        brands: seenBrands.size > 1 ? [...seenBrands].slice(0, 8) : [],
        priceRanges: priceRanges || [],
        category: treeScope ? treeScope.node.ua : intent.category || null,
        brand: intent.brand || null,
        budgetMin: intent.budget_min || null,
        budgetMax: intent.budget_max || null,
        condition: shownCondition,
      };
      if (treeScope && treeScope.nodes.length === 1) suggestedFilters.nodeKey = treeScope.node.k;
      if (treeOptions && treeOptions.length) {
        suggestedFilters.options = treeOptions;
        suggestedFilters.optionsLabel = "Уточнити розділ:";
      }
    }
  } else if (intent.intent === "novelty") {
    // Новинки для запиту про ноутбук: лише нові ноутбуки в наявності (не б/в, без рюкзаків та чохлів)
    const picks = search.findNewest(products, { limit: 8 });
    for (const p of picks) {
      contextLines.push(formatProductLine(p, "НОВИНКА"));
      cards.push(toCard(p, "новинка"));
    }
  } else if (intent.intent === "sale") {
     
     
     
     
     
     
     
     
     
     
     
    const isBroadSaleQuickAction = isBroadSaleRequest(message);
    if (isBroadSaleQuickAction) {
      sessionScope.set(sessionId, { category: null, brand: null, budgetMin: null, budgetMax: null, condition: null });
      effectiveCondition = null;
    }
    saleCategory = search.guessCategoryFromText(message);
    saleBrand = search.guessBrandFromText(message, products);
    if (!saleCategory && !saleBrand && !isBroadSaleQuickAction) {
      const scope = getScope(sessionId);
      saleCategory = scope.category || null;
      saleBrand = scope.brand || null;
    }
    const hasScope = Boolean(saleCategory || saleBrand);
     
     
     
     
    let picks = search.findDiscountedProducts(products, {
      category: hasScope ? saleCategory : null,
      brand: hasScope ? saleBrand : null,
      categories: catalog.categories,
      limit: 24,
    });
    if (hasScope && !picks.length) {
      const regularPicks = search.findByBudget(products, {
        category: saleCategory,
        brand: saleBrand,
        categories: catalog.categories,
        queryText: normalizedText,
        limit: 8,
      });
      noConfirmedSaleForScope = { category: saleCategory, brand: saleBrand };
      picks = regularPicks;
    } else if (!hasScope && !picks.length) {
      noConfirmedSaleForScope = { category: "каталозі" };
    }
    for (const p of picks) {
      const tag = noConfirmedSaleForScope ? "В НАЯВНОСТІ (знижку не підтверджено)" : "РОЗПРОДАЖ";
      contextLines.push(formatProductLine(p, tag));
      cards.push(toCard(p, noConfirmedSaleForScope ? "в наявності" : "розпродаж"));
    }
    if (!noConfirmedSaleForScope && picks.length) {
      contextLines.push("Підказка: якщо потрібен конкретний товар зі знижкою, клієнт може написати модель або категорію — перевіримо окремо.");
    }
  }
   

  // Нічого не знайшли, а LLM на порожньому списку починає вигадувати («у нас немає посуду», хоча він є).
  // Спершу ще раз пробуємо прямий пошук по тому, як LLM переписала запит; далі — детермінована чесна відповідь.
  if (
    !needsClarification &&
    cards.length === 0 &&
    !unavailableSpecificProducts &&
    !noConfirmedSaleForScope &&
    (intent.intent === "specific_product" || intent.intent === "recommendation" || intent.intent === "accessory")
  ) {
    for (const candidate of [intent.search_text, intent.semantic_query, intent.model, intent.category]) {
      if (!candidate || String(candidate).trim().toLowerCase() === String(message).trim().toLowerCase()) continue;
      try {
        const retry = finder.find(catalog, String(candidate));
        if (retry && retry.tier !== "unavailable") return buildFinderResponse({ sessionId, r: retry, message: candidate, catalog, rawMessage });
      } catch (err) {
        console.error("[chat] finder retry error:", err.message);
      }
    }
    return buildNotFoundResponse({ sessionId, message, catalog, rawMessage });
  }

  let contextBlock;
  if (needsClarification) {
    contextBlock = contextLines.join("\n");
  } else if (intent.intent === "smalltalk") {
     
     
     
    contextBlock = "";
  } else if (intent.intent === "other") {
     
     
     
     
    contextBlock = "Це запитання не про конкретний товар — дай відповідь по суті, спираючись на довідку про магазин з інструкцій.";
  } else if (contextLines.length) {
    contextBlock = `Знайдено в каталозі:\n${contextLines.join("\n")}`;
  } else {
    contextBlock = "Знайдено в каталозі: (нічого релевантного не знайдено в поточному кеші каталогу)";
  }

  if (isIdentityProbe) {
    // Деталь: без цієї позначки reply-LLM НЕ МАЄ ПРАВА застосовувати "ухильну" відповідь
    // (див. переписане правило 13) — так товарні питання більше не зможуть випадково під
    // нього підпасти, навіть якщо нічого не знайдено чи повідомлення виглядає дивно.
    contextBlock = `[IDENTITY_PROBE]\n${contextBlock}`;
  }

  if (isReconsider) {
    // Пояснюємо LLM, що буквальне повідомлення клієнта було "думай"/"пошукай ще раз" —
    // це прохання повернутись до попереднього запиту, а НЕ спроба вивідати інструкції
    // (без цієї примітки правило 13 REPLY_SYSTEM_PROMPT іноді хибно спрацьовує на саме
    // слово "думай" і відповідає жартом замість того, щоб дати реальний результат).
    contextBlock =
      `Клієнт написав "${rawMessage}" — це значить "подивись, будь ласка, ще раз на моє попереднє питання: ${message}". ` +
      `Це НЕ спроба вивідати інструкції чи технічні деталі. Почни відповідь короткою теплою фразою на кшталт ` +
      `"Гаразд, подивилась ще раз 🤔" і одразу дай реальну відповідь по суті нижче, без жартів і без ухильних формулювань.\n\n${contextBlock}`;
  }

  let replyText;
  if (noConfirmedSaleForScope) {
    const categoryLabel = noConfirmedSaleForScope.category && /навуш|науш/i.test(noConfirmedSaleForScope.category)
      ? "навушники"
      : noConfirmedSaleForScope.category;
    const target = [noConfirmedSaleForScope.brand, categoryLabel]
      .filter(Boolean)
      .join(" ");
    replyText = target === "каталозі"
      ? "Наразі фід не містить підтверджених знижок: для акційних товарів не передається стара ціна."
      : `Наразі у фіді немає підтвердженої акції або знижки на ${target || "цей товар"}. Нижче показую актуальні товари в наявності.`;
  } else if (unavailableSpecificProducts?.length) {
    replyText = `На жаль, ${unavailableSpecificProducts[0].name} зараз немає в наявності. Не показую його як варіант для покупки.`;
  } else try {
    replyText = await gemini.chat({
      cacheKey: "reply",
      systemInstruction: REPLY_SYSTEM_PROMPT,
      temperature: 0.5,
      maxTokens: 500,
      history: history.slice(-4),
      userText: `Повідомлення користувача: "${message}"\n\n${contextBlock}`,
    });
  } catch (err) {
     
     
     
     
    console.error("[chat] reply generation error:", err.message);
     
     
     
    const mainCards = cards.filter((card) => card.tag !== "аксесуар");
    if (mainCards.length && intent.intent === "specific_product") {
      const names = mainCards.slice(0, 10).map((card) => `${card.name} — ${card.price != null ? `${card.price} грн` : "ціна уточнюється"}`);
      const colors = specificColorSummary
        ? specificColorSummary.replace(/^ДОСТУПНІ КОЛЬОРИ [^:]+:\s*/u, "").replace(/\.\s*$/u, "")
        : null;
      replyText = colors
        ? `Так, ${intent.model} є в наявності у кольорах: ${colors}. Показую актуальні варіанти:\n${names.join("\n")}`
        : `Так, знайшов ${mainCards.length} варіантів у каталозі. Ось актуальні моделі:\n${names.join("\n")}`;
    } else if (mainCards.length) {
      const total = recommendationSummary?.total || mainCards.length;
      const minPrice = recommendationSummary?.minPrice;
      const maxPrice = recommendationSummary?.maxPrice;
      const shownCondition = effectiveCondition || (recommendationSummary?.usedBudgetFallback ? "used" : null);
      const variantLabel = shownCondition === "used"
        ? `${productCountWord(total)} б/в`
        : shownCondition === "new"
        ? total === 1 ? "новий варіант" : "нових варіантів"
        : total === 1 ? "актуальний варіант" : "актуальних варіантів";
      const priceRange = minPrice != null && maxPrice != null ? ` Ціни: від ${minPrice} до ${maxPrice} грн.` : "";
      const displayHint = mainCards.length === 1 ? "Показую її у списку нижче." : `Показую перші ${mainCards.length} у списку нижче.`;
      replyText = `Знайшов ${total} ${variantLabel} у каталозі.${priceRange} ${displayHint}`;
    } else if (effectiveCondition === "used" || effectiveCondition === "new") {
      const conditionLabel = effectiveCondition === "used" ? "б/в товарів" : "нових товарів";
      replyText = `Наразі у фіді немає ${conditionLabel} у наявності за цим запитом. Можу підібрати інший бренд, модель або бюджет.`;
    } else {
      replyText = "Наразі не вдалося отримати відповідь сервісу. Спробуйте ще раз за хвилину.";
    }
  }

   
   
  const CATALOG_INTENTS = new Set(["specific_product", "recommendation", "accessory", "novelty", "sale"]);
  if (!needsClarification && CATALOG_INTENTS.has(intent.intent)) {
    replyText = await selfCheckReply({ replyText, allowedProducts: cards });
  }

  const SCOPE_INTENTS = new Set(["recommendation", "sale", "specific_product", "accessory"]);
  if (SCOPE_INTENTS.has(intent.intent)) {
    updateScope(sessionId, {
      category: (intent.intent === "sale" ? saleCategory : intent.category) || null,
      brand: (intent.intent === "sale" ? saleBrand : intent.brand) || null,
      budgetMin: intent.budget_min || null,
      budgetMax: intent.budget_max || null,
      condition: effectiveCondition,
      nodeKey: treeScope && treeScope.nodes.length === 1 ? treeScope.node.k : null,
    });
  }

  pushHistory(sessionId, "user", rawMessage);
  pushHistory(sessionId, "assistant", replyText);

  return { reply: replyText.trim(), products: cards, intent, filters: suggestedFilters };
}

async function handleMessageSafe(args) {
  try {
    return handleMessage(args);
  } catch (err) {
    console.error("[chat] pipeline error, using deterministic fallback:", err && err.message);
    try {
      const { normalizedText } = slang.normalizeSlang(args.message);
      const found = finder.find(args.catalog, normalizedText);
      if (found) return buildFinderResponse({ sessionId: args.sessionId, r: found, message: args.message, catalog: args.catalog, rawMessage: args.message });
    } catch (fallbackErr) {
      console.error("[chat] fallback search failed:", fallbackErr && fallbackErr.message);
    }
    return {
      reply: "Не вдалося повністю обробити запит. Напишіть, будь ласка, назву товару або бюджет — підберу з каталогу.",
      products: [],
      intent: { intent: "other", confidence: 1, source: "fallback" },
      filters: null,
    };
  }
}

