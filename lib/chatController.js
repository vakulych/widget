function getHistory(sessionId) {
  return sessions.get(sessionId) || [];
}

function pushHistory(sessionId, role, content) {
  const h = getHistory(sessionId);
  h.push({ role, content });
  while (h.length > MAX_HISTORY) h.shift();
  sessions.set(sessionId, h);
}

function safeParseJson(text) {
  try {
    return JSON.parse(text);
  } catch {
    const match = text.match(/\{[\s\S]*\}/);
    if (match) {
      try {
        return JSON.parse(match[0]);
      } catch {
        return null;
      }
    }
    return null;
  }
}

// Постачальник додає в кінець назви технічний код моделі в дужках — "(BHR9956EU)",
// "(AD201EU)", "(MD506Z/A)" — який нічого не каже клієнту, а ще й плутає: суфікс "EU"
// читається як "це для Європи, не для України", хоча насправді це просто код постачальника.
// Відрізняємо такий код від корисних уточнень у дужках ("(Type-A)", "(White)") за регістром:
// код постачальника — ВЕЛИКІ літери/цифри без пробілів, людське уточнення — зі звичайним словом.
// Вимагаємо хоч одну літеру в дужках, інакше заодно зрізало б рік моделі — "ТВ ... (2024)".
const VENDOR_CODE_PAREN_RE = /\s*\((?=[A-Z0-9\-\/]*[A-Z])[A-Z0-9][A-Z0-9\-\/]{2,14}\)\s*$/;
function stripVendorCode(name) {
  let out = String(name || "").trim();
  for (let i = 0; i < 4 && VENDOR_CODE_PAREN_RE.test(out); i++) {
    const next = out.replace(VENDOR_CODE_PAREN_RE, "").trim();
    if (next === out) break;
    out = next;
  }
  return out || String(name || "").trim();
}

function formatProductLine(p, tag) {
  const price = p.price ? `${p.price} грн` : "ціна уточнюється";
  const avail = p.available === false ? "немає в наявності" : "в наявності";
  const tagStr = tag ? `[${tag}] ` : "";
  const variant = productVariantDetails(p);
  // Раніше рядок контексту для reply-LLM взагалі не містив oldPrice/знижку (хоча toCard() для
  // самої картки товару її рахував) — тому модель у ТЕКСТІ відповіді не бачила знижку навіть
  // мінімальну і на пряме питання "чи є знижка на цей товар?" могла відповісти навмання чи
  // ухильно. Тепер позначаємо ЗНИЖКУ явно в самому рядку — без порогу, навіть на 1 грн/1%,
  // якщо oldPrice > price у фіді.
  const hasDiscount = p.oldPrice != null && p.price != null && p.oldPrice > p.price;
  const discountStr = hasDiscount
    ? `, ЗНИЖКА ${Math.round((1 - p.price / p.oldPrice) * 100)}% (було ${p.oldPrice} грн → зараз ${p.price} грн)`
    : "";
  return `${tagStr}${stripVendorCode(p.name)}${variant ? ` (${variant})` : ""} — ${price}${discountStr}, ${avail}${p.url ? `, посилання: ${p.url}` : ""}`;
}

// Колір і обсяг у фіді передаються параметрами, а не завжди є в одній формі в назві.
// Додаємо їх до контексту відповіді, щоб консультант міг чесно перерахувати доступні
// варіанти конкретної моделі, а не лише показати картки.
function productVariantDetails(product) {
  const params = product && product.params && typeof product.params === "object" ? product.params : {};
  const entries = Object.entries(params);
  const valueOf = (re) => {
    const entry = entries.find(([key]) => re.test(String(key).toLowerCase()));
    return entry && entry[1] ? String(entry[1]).trim() : null;
  };
  const color = valueOf(/колір|цвет|color/iu);
  const storage = valueOf(/вбудован.*пам|об.?єм.*пам|storage|память/iu);
  return [["колір", color], ["пам'ять", storage]].filter(([, value]) => value).map(([label, value]) => `${label}: ${value}`).join(", ");
}

const REQUESTED_COLORS = [
  { label: "чорний", re: /чорн|черн|\bblack\b/iu },
  { label: "білий", re: /біл|бел|\bwhite\b/iu },
  { label: "синій", re: /син|голуб|\bblue\b/iu },
  { label: "червоний", re: /червон|красн|бургунд|\bburgundy\b|\bred\b/iu },
  { label: "срібний", re: /сріб|серебр|\bsilver\b/iu },
  { label: "зелений", re: /зелен|олив|\bolive\b|\bgreen\b/iu },
  { label: "рожевий", re: /рожев|розов|маджент|\bmagenta\b|\bpink\b/iu },
  { label: "фіолетовий", re: /фіолет|фиолет|\bpurple\b/iu },
  { label: "золотий", re: /золот|\bgold\b/iu },
];

function requestedColors(message) {
  return REQUESTED_COLORS.filter(({ re }) => re.test(String(message || ""))).map(({ label }) => label);
}

function productMatchesRequestedColor(product, colors) {
  if (!colors.length) return true;
  const details = `${product.name || ""} ${Object.values(product.params || {}).join(" ")}`;
  return REQUESTED_COLORS.some(({ label, re }) => colors.includes(label) && re.test(details));
}

function productMatchesExactModel(product, model) {
  if (!model) return true;
  if (/^iphone\s+\d+/iu.test(model)) {
    const expected = String(model).toLowerCase().replace(/\s+/g, " ").trim();
    const actual = String(product.name || "").match(/\b(iPhone\s+\d+(?:\s+(?:Pro\s+Max|Pro|Plus|mini|Air|SE))?)/iu);
    return Boolean(actual && actual[1].toLowerCase().replace(/\s+/g, " ") === expected);
  }
  const productTokens = new Set(search.tokens(product.name || ""));
  return search.tokens(model).every((token) => productTokens.has(token));
}

function availableVariantSummary(products, model) {
  const variants = products.filter((p) => p.available !== false);
  const colors = [...new Set(variants.map((p) => productVariantDetails(p).match(/колір: ([^,]+)/u)?.[1]).filter(Boolean))];
  if (!colors.length) return null;
  return `ДОСТУПНІ КОЛЬОРИ ${model}: ${colors.join(", ")}.`;
}

function toCard(p, tag) {
   
   
   
  const hasDiscount = p.oldPrice && p.price && p.oldPrice > p.price;
  return {
    id: p.id,
    name: stripVendorCode(p.name),
    price: p.price,
    oldPrice: hasDiscount ? p.oldPrice : null,
    discountPct: hasDiscount ? Math.round((1 - p.price / p.oldPrice) * 100) : null,
    currency: p.currency,
    url: p.url,
    picture: p.picture,
    available: p.available !== false,
    tag: tag || null,
  };
}

function uniqueProducts(products) {
  const seen = new Set();
  return products.filter((p) => {
    const key = `${stripVendorCode(p.name || "").toLowerCase().replace(/\s+/g, " ")}|${p.price || ""}`;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

function accessoryIphoneModel(message) {
  const m = /(?:iphone|айфон)?\s*(1[0-9])\s*(pro\s*max|про\s*макс|pro|про|plus|плюс|mini|міні|мини|air|se)?/iu.exec(String(message || ""));
  if (!m) return null;
  const variant = String(m[2] || "").toLowerCase()
    .replace(/про/gu, "pro").replace(/макс/gu, "max").replace(/плюс/gu, "plus")
    .replace(/міні|мини/gu, "mini").replace(/\s+/g, " ").trim();
  return `iPhone ${m[1]}${variant ? ` ${variant.replace(/\b\p{L}/gu, (x) => x.toUpperCase())}` : ""}`;
}

