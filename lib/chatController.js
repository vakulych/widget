  pushHistory(sessionId, "user", rawMessage);
  pushHistory(sessionId, "assistant", reply);
  return { reply, products: products.slice(0, 8).map((p) => toCard(p, "аксесуар")), intent: { intent: "accessory", confidence: 1, source: "iphone-accessory-exact" }, filters: null };
